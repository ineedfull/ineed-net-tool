import { test, expect, _electron as electron } from '@playwright/test';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { emptyWorkspace, newProject } from '../../src/domain/projects.js';
const root = fileURLToPath(new URL('../..', import.meta.url));
const require = createRequire(import.meta.url);

test('project planning preserves tab drafts, isolates projects and roundtrips JSON without losing the ledger', async ({}, info) => {
  const folder = await fs.mkdtemp(path.join(os.tmpdir(), 'nettool-project-planning-'));
  const state = emptyWorkspace();
  state.projects.push(newProject('site-b', '现场 B'));
  state.networks.push({ id: 'legacy', projectId: 'default-project', name: '办公网络', cidr: '192.168.1.0/24', note: '现场备注', gateway: '192.168.1.254', vlan: 10, dhcpStart: '192.168.1.100', dhcpEnd: '192.168.1.150', allocations: [{ ip: '192.168.1.10', label: 'PLC' }] });
  await fs.writeFile(path.join(folder, 'workspace.json'), JSON.stringify(state));
  let app;
  try {
    app = await electron.launch({ executablePath: process.env.ELECTRON_BINARY || require('electron'), args: [root], env: { ...process.env, NET_TOOL_TEST_DATA: folder } });
    const page = await app.firstWindow();
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    const click = name => page.getByRole('button', { name, exact: true }).click();
    const tab = name => page.getByRole('tab', { name, exact: true });
    await expect(tab('地址规划')).toHaveAttribute('aria-selected', 'true');
    await expect(page.getByRole('button', { name: 'IPv4 地址规划', exact: true })).toHaveCount(0);
    await expect(page.locator('.network-table')).toContainText('VLAN 10');
    await expect(page.locator('.network-table')).toContainText('DHCP 192.168.1.100 ～ 192.168.1.150');
    await click('编辑 办公网络');
    await page.getByLabel('网段名称', { exact: true }).fill('尚未保存的名称');
    await tab('IP 地址台账').click();
    await expect(page.locator('.ledger-table')).toContainText('PLC');
    await expect(page.getByLabel('网段名称', { exact: true })).toHaveCount(0);
    await click('Ping 工具');
    await click('项目工作台');
    await expect(tab('IP 地址台账')).toHaveAttribute('aria-selected', 'true');
    await tab('地址规划').click();
    await expect(page.getByLabel('网段名称', { exact: true })).toHaveValue('尚未保存的名称');
    await click('保存修改');
    await expect(page.getByRole('status')).toContainText('网段规划已保存');
    await click('新建');
    await page.getByLabel('网段名称', { exact: true }).fill('不能带到其他项目的草稿');
    await click('Ping 工具');
    await page.getByLabel('当前项目').selectOption('site-b');
    await click('项目工作台');
    await expect(page.getByLabel('网段名称', { exact: true })).toHaveValue('');
    await expect(page.locator('.network-table')).toHaveCount(0);
    await page.getByLabel('网段名称', { exact: true }).fill('B 项目网段');
    await page.getByLabel('IP 地址或 CIDR').fill('10.2.0.0/24');
    await click('保存网段');
    await expect(page.getByRole('status')).toContainText('网段规划已保存');
    let saved = await page.evaluate(() => window.netTool.load());
    expect(saved.networks.find(n => n.id === 'legacy')).toEqual({ ...state.networks[0], name: '尚未保存的名称' });
    expect(saved.networks.find(n => n.name === 'B 项目网段').projectId).toBe('site-b');
    const exported = path.join(folder, 'plans.json');
    await app.evaluate(({ dialog }, file) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: file }); }, exported);
    await click('导出 JSON 规划');
    await expect.poll(() => fs.readFile(exported, 'utf8').then(JSON.parse).then(d => d.networks.length).catch(() => 0)).toBe(1);
    await app.evaluate(({ dialog }, file) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }); }, exported);
    await click('导入 JSON 规划');
    await expect(page.getByRole('status')).toContainText('已合并 0 个网段');
    await page.getByLabel('当前项目').selectOption('default-project');
    await click('编辑 尚未保存的名称');
    await page.locator('.page-content').evaluate(el => { el.style.scrollBehavior = 'auto'; el.scrollTop = 0; });
    await page.screenshot({ path: info.outputPath('project-planning-light.png'), scale: 'css' });
    await click('设置');
    await page.getByLabel('主题', { exact: true }).selectOption('dark');
    await page.getByLabel('大字模式', { exact: true }).check();
    await click('保存设置');
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(960, 720));
    expect(await page.locator('.page-content').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
    await page.locator('.network-table').scrollIntoViewIfNeeded();
    const deletion = page.getByRole('button', { name: '删除 尚未保存的名称', exact: true });
    await page.screenshot({ path: info.outputPath('project-planning-dark-960.png'), scale: 'css' });
    await expect(deletion).toBeInViewport();
    await tab('IP 地址台账').click();
    await expect(page.locator('.ledger-table')).toContainText('PLC');
    expect(errors).toEqual([]);
  } finally { if (app) await app.close(); await fs.rm(folder, { recursive: true, force: true }); }
});
