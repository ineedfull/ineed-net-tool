import { test, expect, _electron as electron } from '@playwright/test';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { emptyWorkspace, newProject } from '../../src/domain/projects.js';
const root = fileURLToPath(new URL('../..', import.meta.url));
const require = createRequire(import.meta.url);
const executablePath = process.env.ELECTRON_BINARY || require('electron');

test('independent calculation preserves drafts and appends single or split networks to the chosen project', async ({}, info) => {
  const folder = await fs.mkdtemp(path.join(os.tmpdir(), 'nettool-calculator-'));
  const state = emptyWorkspace();
  state.projects.push(newProject('site-b', '现场 B'));
  state.networks.push({ id: 'legacy', projectId: 'default-project', name: '旧网段', cidr: '192.168.1.0/24', note: '保留', gateway: '192.168.1.254', vlan: 10, dhcpStart: '192.168.1.100', dhcpEnd: '192.168.1.150', allocations: [{ ip: '192.168.1.10', label: 'PLC' }] });
  state.history.push({ id: 'old', kind: 'ping', projectId: 'default-project', target: '127.0.0.1', startedAt: '2026-09-21T00:00:00Z', status: 'completed', rows: [] });
  await fs.writeFile(path.join(folder, 'workspace.json'), JSON.stringify(state));
  let app;
  const launch = () => electron.launch({ executablePath, args: [root], env: { ...process.env, NET_TOOL_TEST_DATA: folder } });
  try {
    app = await launch(); let page = await app.firstWindow();
    const errors = []; page.on('pageerror', error => errors.push(error.message));
    const click = name => page.getByRole('button', { name, exact: true }).click();
    await click('编辑 旧网段');
    await page.getByLabel('网段名称', { exact: true }).fill('尚未保存的修改');
    await expect(page.getByRole('button', { name: '生成划分方案', exact: true })).toHaveCount(0);
    await click('网段计算');
    await expect(page.getByLabel('当前项目')).toHaveCount(0);
    await expect(page.getByLabel('默认网关', { exact: true })).toHaveCount(0);
    await expect(page.locator('.multicast-detail')).toContainText('239.255.255.255');
    await page.getByLabel('IP 地址或 CIDR').fill('10.20.30.77');
    await page.getByLabel('子网掩码', { exact: true }).fill('255.255.255.192');
    await expect(page.locator('.metrics')).toContainText('10.20.30.64');
    await expect(page.locator('.range-strip')).toContainText('10.20.30.126');
    await click('加入项目规划');
    await page.getByLabel('保存到项目').selectOption('site-b');
    await page.getByLabel('保存网段名称 1', { exact: true }).fill('计算保存的网段');
    await click('取消');
    expect((await page.evaluate(() => window.netTool.load())).networks).toHaveLength(1);
    await click('加入项目规划');
    await page.getByLabel('保存到项目').selectOption('site-b');
    await page.getByLabel('保存网段名称 1', { exact: true }).fill('计算保存的网段');
    await click('保存到项目');
    await expect(page.getByRole('status')).toContainText('现场 B');
    let saved = await page.evaluate(() => window.netTool.load());
    expect(saved.activeProjectId).toBe('default-project');
    expect(saved.networks.find(n => n.id === 'legacy')).toEqual(state.networks[0]);
    expect(saved.networks.find(n => n.name === '计算保存的网段')).toMatchObject({ projectId: 'site-b', cidr: '10.20.30.64/26', gateway: '' });
    await click('项目工作台');
    await expect(page.getByLabel('网段名称', { exact: true })).toHaveValue('尚未保存的修改');
    await click('网段计算');
    await expect(page.getByLabel('IP 地址或 CIDR')).toHaveValue('10.20.30.77');
    await expect(page.getByLabel('子网掩码', { exact: true })).toHaveValue('255.255.255.192');
    await page.getByLabel('子网掩码', { exact: true }).fill('');
    await page.getByLabel('IP 地址或 CIDR').fill('192.168.1.0/24');
    await click('生成划分方案');
    await expect(page.locator('tbody tr')).toHaveCount(3);
    await click('将划分结果加入项目');
    await expect(page.getByRole('dialog')).toContainText('旧网段');
    await page.getByLabel('保存到项目').selectOption('site-b');
    await expect(page.getByRole('dialog').locator('.warning')).toHaveCount(0);
    await click('保存到项目');
    await expect(page.getByRole('status')).toContainText('3 个网段');
    await click('DNS 查询'); await click('网段计算');
    await expect(page.locator('tbody tr')).toHaveCount(3);
    await page.locator('.page-content').evaluate(el => { el.scrollTop = 0; });
    await page.screenshot({ path: info.outputPath('calculator-light.png'), scale: 'css' });
    await click('探测此网段');
    await expect(page.getByLabel('scan目标')).toHaveValue('192.168.1.0/24');
    await expect(page.locator('.section-heading .badge').first()).toHaveText('就绪');
    await click('网段计算');
    await page.getByLabel('IP 地址或 CIDR').fill('10.0.0.0/31');
    await expect(page.locator('tbody tr')).toHaveCount(0);
    await expect(page.locator('.range-strip')).toContainText('点对点');
    await expect(page.locator('.network-details')).toContainText('无通用建议');
    await page.getByLabel('IP 地址或 CIDR').fill('10.0.0.7/32');
    await expect(page.locator('.range-strip')).toContainText('单主机地址');
    await page.getByLabel('子网掩码', { exact: true }).fill('255.0.255.0');
    await expect(page.getByRole('alert')).toContainText('连续');
    await expect(page.getByRole('button', { name: '加入项目规划', exact: true })).toBeDisabled();
    await page.getByLabel('子网掩码', { exact: true }).fill('');
    await page.getByLabel('IP 地址或 CIDR').fill('192.168.1.0/24');
    await click('生成划分方案');
    await click('设置');
    await page.getByLabel('主题', { exact: true }).selectOption('dark');
    await page.getByLabel('大字模式', { exact: true }).check();
    await click('保存设置');
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(960, 720));
    await page.locator('.page-content').evaluate(el => { el.scrollTop = 0; });
    expect(await page.locator('.page-content').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
    await page.screenshot({ path: info.outputPath('calculator-dark-960.png'), scale: 'css' });
    await click('将划分结果加入项目');
    await expect(page.getByRole('dialog')).toBeVisible();
    expect(await page.getByRole('dialog').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
    await page.screenshot({ path: info.outputPath('calculator-save-dark.png'), scale: 'css' });
    await page.keyboard.press('Escape');
    expect(errors).toEqual([]);
    await app.close(); app = await launch(); page = await app.firstWindow();
    saved = await page.evaluate(() => window.netTool.load());
    expect(saved.networks).toHaveLength(5);
    expect(saved.networks.filter(n => n.projectId === 'site-b')).toHaveLength(4);
    expect(saved.networks.find(n => n.id === 'legacy')).toEqual(state.networks[0]);
    expect(saved.history).toEqual(state.history);
    await page.getByLabel('当前项目').selectOption('site-b');
    await expect(page.getByRole('button', { name: '编辑 计算保存的网段', exact: true })).toBeVisible();
  } finally { if (app) await app.close(); await fs.rm(folder, { recursive: true, force: true }); }
});

test('calculator works even when the project workspace cannot load', async () => {
  const folder = await fs.mkdtemp(path.join(os.tmpdir(), 'nettool-calculator-offline-'));
  await fs.writeFile(path.join(folder, 'workspace.json'), '{broken');
  let app;
  try {
    app = await electron.launch({ executablePath, args: [root], env: { ...process.env, NET_TOOL_TEST_DATA: folder } });
    const page = await app.firstWindow();
    await expect(page.getByRole('heading', { name: '工作区未能加载' })).toBeVisible();
    await page.getByRole('button', { name: '网段计算', exact: true }).click();
    await page.getByLabel('IP 地址或 CIDR').fill('10.1.2.3/16');
    await expect(page.locator('.metrics')).toContainText('10.1.0.0');
    await page.getByRole('button', { name: '生成划分方案', exact: true }).click();
    await expect(page.locator('tbody tr')).toHaveCount(3);
    await expect(page.getByRole('button', { name: '加入项目规划', exact: true })).toBeDisabled();
    expect(await fs.readFile(path.join(folder, 'workspace.json'), 'utf8')).toBe('{broken');
  } finally { if (app) await app.close(); await fs.rm(folder, { recursive: true, force: true }); }
});
