import {test,expect,_electron as electron} from '@playwright/test';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';
import fixtureModule from '../helpers/network-fixtures.cjs';
const root=fileURLToPath(new URL('../..',import.meta.url));
const require=createRequire(import.meta.url);
const executablePath=process.env.ELECTRON_BINARY || require('electron');
test('DNS, ports, quality, download and certificate pages persist real local results and export',async({},info)=>{
  const servers=await fixtureModule.fixtures();
  const folder=await fs.mkdtemp(path.join(os.tmpdir(),'nettool-extended-ui-'));let app;
  const launch=()=>electron.launch({executablePath,args:[root],env:{...process.env,NET_TOOL_TEST_DATA:folder}});
  const old={id:'old-ping',kind:'ping',target:'127.0.0.1',startedAt:'2026-01-01T00:00:00Z',status:'completed',completed:1,rows:[{seq:1,ip:'127.0.0.1',status:'reachable',ms:1}]};
  await fs.writeFile(path.join(folder,'workspace.json'),JSON.stringify({version:1,networks:[],settings:{theme:'light',largeFont:false},history:[old]}));
  try{
    app=await launch();let page=await app.firstWindow();const errors=[];page.on('pageerror',error=>errors.push(error.message));
    const navigate=name=>page.getByRole('button',{name,exact:true}).click();
    const complete=()=>expect(page.locator('.section-heading .badge').first()).toHaveText('已完成');
    await navigate('DNS 查询');
    await page.getByLabel('dns目标').fill('example.test');
    await page.getByLabel('DNS 服务器',{exact:true}).fill(`127.0.0.1:${servers.dnsPort}`);
    await navigate('开始测试');await complete();
    await expect(page.locator('.tool-results tbody')).toContainText('127.0.0.1');
    await expect(page.locator('.tool-results tbody')).toContainText('60');
    await navigate('端口扫描');await page.getByLabel('ports目标').fill('127.0.0.1');
    await page.getByLabel('扫描端口',{exact:true}).fill(`${servers.openPort},${servers.closedPort}`);
    await navigate('开始测试');await complete();
    await expect(page.locator('.tool-results tbody tr')).toHaveCount(2);
    await page.getByLabel('端口状态筛选').selectOption('open');
    await expect(page.locator('.tool-results tbody tr')).toHaveCount(1);
    await expect(page.locator('.tool-results tbody')).toContainText(String(servers.openPort));
    await navigate('网速与质量');await navigate('链路质量');
    await page.getByLabel('质量测试方式').selectOption('tcp');
    await page.getByLabel('质量测试端口').fill(String(servers.openPort));
    await page.getByLabel('质量采样次数').fill('3');await page.getByLabel('质量采样间隔').fill('200');
    await navigate('开始测试');await navigate('DNS 查询');await navigate('网速与质量');await complete();
    await expect(page.locator('.tool-results')).toContainText('0.00%');
    await expect(page.locator('.tool-results tbody tr')).toHaveCount(3);
    await navigate('下载测速');await page.getByLabel('speed目标').fill(servers.url+'/stream');
    await page.getByLabel('测速秒数').fill('1');await page.getByLabel('测速流量上限').fill('4');
    await navigate('开始测试');await complete();
    await expect(page.locator('.tool-results')).toContainText('达到设定时长');
    await app.evaluate(({dialog},file)=>{dialog.showSaveDialog=async()=>({canceled:false,filePath:file});},path.join(folder,'speed.json'));
    await navigate('导出结果');
    await expect.poll(async()=>fs.readFile(path.join(folder,'speed.json'),'utf8').then(JSON.parse).then(r=>r.summary.bytes).catch(()=>0)).toBeGreaterThan(0);
    await navigate('证书检查');await page.getByLabel('certificate目标').fill('127.0.0.1');
    await page.getByLabel('TLS 端口',{exact:true}).fill(String(servers.tlsPort));
    await page.getByLabel('证书校验域名').fill('localhost');
    await navigate('开始测试');await complete();
    await expect(page.locator('.tool-results')).toContainText('即将到期');
    await expect(page.locator('.tool-results')).toContainText('未通过');
    await expect(page.locator('.tool-results')).toContainText('localhost');
    const displayedDates = page.locator('.tool-details > div').filter({ has: page.locator('dt', { hasText: /^(生效时间|到期时间)$/ }) }).locator('dd');
    await expect(displayedDates).toHaveCount(2);
    for (const date of await displayedDates.allTextContents()) expect(date).toMatch(/^\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2}\.\d{3}$/);
    const validity = await page.evaluate(() => window.netTool.load().then(state => state.history.find(row => row.kind === 'certificate').summary));
    expect(validity.validFrom).toMatch(/ GMT$/);
    expect(validity.validTo).toMatch(/ GMT$/);
    const displayedEpochs = await displayedDates.evaluateAll(nodes => nodes.map(node => Date.parse(node.textContent.replace(' ', 'T'))));
    expect(displayedEpochs).toEqual([Date.parse(validity.validFrom), Date.parse(validity.validTo)]);
    await page.locator('.tool-results').scrollIntoViewIfNeeded();
    await page.screenshot({path:info.outputPath('certificate-light.png'),scale:'css'});
    const state=await page.evaluate(()=>window.netTool.load());
    expect(state.history).toHaveLength(6);
    for(const kind of ['dns','ports','quality','speed','certificate'])expect(state.history.find(r=>r.kind===kind).summary).toBeTruthy();
    expect(state.history.find(r=>r.id==='old-ping').rows).toEqual(old.rows);
    await navigate('设置');await page.getByLabel('主题',{exact:true}).selectOption('dark');
    await page.getByLabel('大字模式',{exact:true}).check();await navigate('保存设置');
    await app.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(960,720));
    await page.locator('.tool-results').scrollIntoViewIfNeeded();
    expect(await page.locator('.page-content').evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true);
    await page.screenshot({path:info.outputPath('certificate-dark-960.png'),scale:'css'});
    for(const name of ['DNS 查询','端口扫描','网速与质量']){
      await navigate(name);
      expect(await page.locator('.page-content').evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true);
    }
    expect(errors).toEqual([]);
    await app.close();app=await launch();page=await app.firstWindow();
    await page.getByRole('button',{name:'诊断记录',exact:true}).click();
    for(const name of ['DNS 查询','端口扫描','链路质量','下载测速','证书检查']){
      await page.locator('tbody tr').filter({has:page.getByRole('cell',{name,exact:true})}).getByRole('button',{name:'查看记录'}).click();
      await expect(page.locator('.tool-results')).toBeVisible();
      await expect(page.locator('.tool-results')).not.toContainText('结果将在测试后显示');
      await page.getByRole('button',{name:'关闭诊断详情',exact:true}).click();
    }
  }finally{if(app)await app.close();await servers.close();await fs.rm(folder,{recursive:true,force:true});}
});
