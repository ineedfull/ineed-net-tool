import { test, expect, _electron as electron } from '@playwright/test';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
const root = fileURLToPath(new URL('../..', import.meta.url));
const executablePath = process.env.ELECTRON_BINARY || createRequire(import.meta.url)('electron');
test('editable subnet plans validate capacity and overlap and persist chosen gateways', async ({}, info) => {
  const folder = await fs.mkdtemp(path.join(os.tmpdir(), 'nettool-subnet-edit-'));
  let app;
  const launch = () => electron.launch({ executablePath, args: [root], env: { ...process.env, NET_TOOL_TEST_DATA: folder } });
  try {
    app = await launch(); let page = await app.firstWindow();
    const errors = []; page.on('pageerror', e => errors.push(e.message));
    const click = name => page.getByRole('button', { name, exact: true }).click();
    await click('网段计算'); await click('生成划分方案');
    const rows = page.locator('.subnet-results tbody tr');
    await expect(rows).toHaveCount(3);
    await expect(rows.first()).toContainText('192.168.1.63');
    await expect(rows.nth(1)).toContainText('192.168.1.127');
    await expect(rows.first()).toContainText('未设置');
    await click('新增子网需求');
    await page.getByLabel('子网用途 4', { exact: true }).fill('研发');
    await page.getByLabel('设备数量 4', { exact: true }).fill('5');
    await page.getByLabel('预留数量 4', { exact: true }).fill('3');
    await expect(page.getByRole('button', { name: '将划分结果加入项目', exact: true })).toBeDisabled();
    await click('生成划分方案'); await expect(rows).toHaveCount(4);
    await click('编辑子网 办公终端');
    const dialog = page.getByRole('dialog', { name: '编辑子网', exact: true });
    await page.getByLabel('编辑子网用途').fill('办公已编辑');
    await page.getByLabel('编辑设备数量').fill('65');
    await expect(dialog.getByRole('alert')).toContainText('容量不足');
    await expect(dialog.getByRole('button', { name: '应用修改', exact: true })).toBeDisabled();
    await page.getByLabel('编辑子网 CIDR').fill('192.168.1.128/25');
    await expect(dialog.getByRole('alert')).toContainText('重叠');
    await page.getByLabel('编辑子网 CIDR').fill('192.168.2.0/25');
    await expect(dialog.getByRole('alert')).toContainText('超出父网段');
    await page.getByLabel('编辑子网 CIDR').fill('192.168.1.5/25');
    await expect(dialog.getByRole('alert')).toContainText('对齐');
    await page.getByLabel('编辑设备数量').fill('60');
    await page.getByLabel('编辑子网 CIDR').fill('192.168.1.0/26');
    await page.getByLabel('编辑默认网关').fill('192.168.1.63');
    await expect(dialog.getByRole('alert')).toContainText('可用地址范围');
    await page.getByLabel('编辑默认网关').fill('192.168.1.62');
    await click('应用修改');
    await expect(rows.first()).toContainText('办公已编辑');
    await expect(page.getByLabel('子网用途 1', { exact: true })).toHaveValue('办公已编辑');
    await click('编辑子网 生产设备');
    await page.getByLabel('编辑子网 CIDR').fill('192.168.1.192/26');
    await expect(dialog).toContainText('广播地址 192.168.1.255');
    await click('使用建议网关');
    await expect(page.getByLabel('编辑默认网关')).toHaveValue('192.168.1.193');
    await click('应用修改');
    await expect(rows.nth(1)).toContainText('192.168.1.255');
    await click('编辑子网 生产设备');
    await page.getByLabel('编辑默认网关').fill('192.168.1.194'); await click('取消');
    await expect(rows.nth(1)).toContainText('192.168.1.193');
    await click('采用全部网关建议');
    await expect(rows.first()).toContainText('192.168.1.62');
    await click('删除子网 研发'); await expect(rows).toHaveCount(3);
    await expect(page.locator('.subnet-demand')).toHaveCount(3);
    await click('DNS 查询'); await click('网段计算');
    await expect(rows.nth(1)).toContainText('192.168.1.192/26');
    await page.locator('.subnet-results').scrollIntoViewIfNeeded();
    await page.screenshot({ path: info.outputPath('subnet-edit-light.png'), scale: 'css' });
    await click('设置'); await page.getByLabel('主题', { exact: true }).selectOption('dark');
    await page.getByLabel('大字模式', { exact: true }).check(); await click('保存设置');
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(960, 720));
    await page.locator('.subnet-results').scrollIntoViewIfNeeded();
    expect(await page.locator('.page-content').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
    expect(await page.locator('.subnet-results').evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true);
    expect(await page.locator('.subnet-results td').evaluateAll(cells => cells.every(el => el.scrollHeight <= el.clientHeight + 1))).toBe(true);
    await expect(page.getByRole('button', { name: '删除子网 办公已编辑', exact: true })).toBeVisible();
    await page.screenshot({ path: info.outputPath('subnet-edit-dark-960.png'), scale: 'css' });
    await click('将划分结果加入项目');
    await expect(page.getByRole('dialog')).toContainText('网关 192.168.1.193');
    await click('保存到项目'); await expect(page.getByRole('status')).toContainText('3 个网段');
    let saved = await page.evaluate(() => window.netTool.load());
    expect(saved.networks.find(n => n.name === '办公已编辑')).toMatchObject({ cidr: '192.168.1.0/26', gateway: '192.168.1.62' });
    expect(saved.networks.find(n => n.name === '生产设备')).toMatchObject({ cidr: '192.168.1.192/26', gateway: '192.168.1.193' });
    expect(errors).toEqual([]);
    await app.close(); app = await launch(); page = await app.firstWindow();
    await page.getByRole('button', { name: '编辑 生产设备', exact: true }).click();
    await expect(page.getByLabel('默认网关', { exact: true })).toHaveValue('192.168.1.193');
    expect((await page.evaluate(() => window.netTool.load())).networks).toEqual(saved.networks);
  } finally { if (app) await app.close(); await fs.rm(folder, { recursive: true, force: true }); }
});
