// Maximum supported real TCP workloads, exclusively 127.0.0.0/16 and 127.0.0.1.
import { _electron as electron, expect } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
import { prepareElectronExecutable } from './dev-electron.mjs';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('..', import.meta.url));
const folder = await fs.mkdtemp('/tmp/nettool-boundaries-');
const report = { folder, testedAt: new Date().toISOString(), cases: [], errors: [] };
const launch = async () => electron.launch({ executablePath: process.env.ELECTRON_BINARY || await prepareElectronExecutable(), args: [root], env: { ...process.env, NET_TOOL_TEST_DATA: path.join(folder, 'data') } });
let app;
try {
  app = await launch(); let page = await app.firstWindow();
  page.on('pageerror', e => report.errors.push(e.message));
  await page.getByRole('button', { name: 'IP 地址探测', exact: true }).click();
  await page.getByLabel('scan目标').fill('127.0.0.0/16');
  await page.getByLabel('探测方式', { exact: true }).selectOption('tcp');
  await page.getByLabel('TCP 端口', { exact: true }).fill('1');
  await page.getByLabel('扫描并发数').fill('128');
  await page.getByLabel('超时毫秒', { exact: true }).fill('100');
  await page.getByRole('button', { name: '开始探测', exact: true }).click();
  await page.getByRole('button', { name: '暂停', exact: true }).click();
  await expect(page.locator('.section-heading .badge').first()).toHaveText('已暂停');
  await page.getByRole('button', { name: '继续', exact: true }).click();
  await page.getByRole('button', { name: 'Ping 工具', exact: true }).click();
  await page.getByRole('button', { name: 'IP 地址探测', exact: true }).click();
  await expect(page.locator('.section-heading .badge').first()).toHaveText('已完成', { timeout: 120000 });
  await expect(page.locator('.result-panel tbody tr')).toHaveCount(100);
  await page.getByLabel('结果页码').selectOption('656');
  await expect(page.locator('.result-panel tbody tr')).toHaveCount(34);
  await expect(page.locator('.result-panel tbody tr').last()).toContainText('127.0.255.254');
  let state = await page.evaluate(() => window.netTool.load());
  const scan = state.history.find(r => r.kind === 'scan');
  expect(scan.rows).toHaveLength(65534); expect(scan.completed).toBe(65534);
  await app.evaluate(({ dialog }, file) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: file }); }, path.join(folder, 'scan.json'));
  await page.getByRole('button', { name: '导出结果', exact: true }).click();
  await expect.poll(async () => fs.readFile(path.join(folder, 'scan.json'), 'utf8').then(JSON.parse).then(r => r.rows.length).catch(() => 0)).toBe(65534);
  report.cases.push({ kind: 'scan', completed: scan.completed, elapsedMs: scan.elapsedMs, retained: scan.rows.length, exported: 65534, nativeMethod: 'TCP', concurrency: 128, pauseResume: true });
  await page.getByRole('button', { name: '端口扫描', exact: true }).click();
  await page.getByLabel('ports目标').fill('127.0.0.1');
  await page.getByLabel('扫描端口', { exact: true }).fill('1-65535');
  await page.getByLabel('端口扫描并发').fill('128');
  await page.getByLabel('工具超时毫秒').fill('100');
  await page.getByRole('button', { name: '开始测试', exact: true }).click();
  await expect(page.locator('.section-heading .badge').first()).toHaveText('已完成', { timeout: 120000 });
  await expect(page.locator('.tool-results tbody tr')).toHaveCount(100);
  state = await page.evaluate(() => window.netTool.load());
  const ports = state.history.find(r => r.kind === 'ports');
  expect(ports.rows).toHaveLength(65535); expect(ports.completed).toBe(65535);
  expect(new Set(ports.rows.map(r => r.port)).size).toBe(65535);
  report.cases.push({ kind: 'ports', completed: ports.completed, elapsedMs: ports.elapsedMs, retained: ports.rows.length, concurrency: 128, summary: ports.summary });
  report.beforeRestart = state.history.map(r => ({ id: r.id, kind: r.kind, rows: r.rows.length }));
  await app.close(); app = await launch(); page = await app.firstWindow();
  const after = await page.evaluate(() => window.netTool.load());
  expect(after.history.map(r => ({ id: r.id, kind: r.kind, rows: r.rows.length }))).toEqual(report.beforeRestart);
  report.restartPreserved = true;
  report.handles = await app.evaluate(() => process._getActiveHandles().map(h => h.constructor.name));
  expect(report.handles.includes('ChildProcess')).toBe(false);
  expect(report.errors).toEqual([]); report.passed = true;
} catch (error) { report.passed = false; report.failure = error.stack; throw error; }
finally { if (app) await app.close(); await fs.writeFile(path.join(folder, 'report.json'), JSON.stringify(report, null, 2)); console.log(JSON.stringify(report)); }
